// API drift check (backlog #205).
//
// Why: the frontend has no codegen — every endpoint string and DTO type
// in frontend/src/api/*.ts is hand-written against the backend, and the
// backend-side contract test (#125, OpenApiContractTest) pins only the
// spec itself. A renamed or removed backend path therefore stayed green
// until a user clicked the dead call. This script is the other half of
// the contract: it extracts every method+path the frontend api modules
// call and fails when one is absent from the OpenAPI document.
//
// Honest scope (backlog #258 extends #205, #264 extends #258, #271
// types the last blind spots, #274 adds the third tranche): paths +
// methods for every frontend api call, PLUS request/response shapes
// for the pinned tranches in api-shape-pins.mjs (auth session core +
// orders surface + items/messages/notifications/reviews surfaces +
// offers/payouts/disputes surfaces). A renamed request/response field
// on a pinned operation fails this gate; unpinned surfaces
// (2FA/passkey/session/device auth) stay path+method-only.
// Register/login success bodies are pinned per status since #271
// (the two success variants each carry a typed envelope now); see
// the pins file header for the full mechanism. Two operations in the
// #264 tranche carry no envelope object at all and are pinned in
// their own forms instead of the field-map form: the SSE stream
// (GET /api/notifications/stream, an event stream, not a JSON body)
// and DELETE /api/notifications/{id} (the SPA reads no body) stay
// path+method-only. The #274 tranche adds one more explicitly
// unpinned operation: DELETE /api/disputes/{disputeId}/evidence/
// {evidenceId} answers ApiResponseVoid and the SPA reads no body, so
// its pin carries a responseNote and the gate's summary lists it as
// response-unpinned. The header says exactly that so nobody reads
// more into a green run.
//
// How the spec gets here: the document is generated by springdoc from
// the controllers (the #95/#125 contract). It is exported by the
// env-gated OpenApiExportTest on the existing contract-test path:
//
//   OPENAPI_EXPORT_PATH=$PWD/frontend/openapi.json \
//     mvn -f backend/pom.xml test -Dtest=com.toni.marketplace.common.OpenApiExportTest
//
// The exported file is a build artifact (gitignored), never committed.
// CI runs exactly those two steps in the `api-drift` job, then
// `npm run check:api`. Locally: export once, then `npm run check:api`.
//
// Extraction rules (pinned by check-api-drift.test.mjs):
//   - calls on the shared `api` axios instance (baseURL '/api'), in both
//     forms used in this codebase: `api.get<...>(url)` and the chained
//     `api` newline `.get<...>(url)`; plus the one raw
//     `axios.post('/api/auth/refresh', ...)` in client.ts;
//   - `new EventSource(url)` counts as a GET (the #203 SSE stream);
//   - only *.ts modules under src/api are scanned, never *.test.* —
//     tests mock the api instance with fixture paths on purpose;
//   - comments are stripped first, so the doc comments that document
//     each endpoint ("GET /api/items/{id} — ...") are never mistaken
//     for calls;
//   - template interpolations (${id}, ${input.itemId},
//     ${encodeURIComponent(id)}) become path params, and matching is
//     param-name-insensitive: a segment that is a param on either side
//     matches a param segment on the other ({id} vs ${userId} is the
//     same call — the backend and the SPA name params independently);
//   - query strings are stripped (params travel via axios `params`,
//     and the one URL-carried query — the SSE ticket — is not part of
//     the path contract).
// A call whose URL is not a string literal fails the gate as
// unextractable rather than being skipped silently: drift must not be
// able to hide behind a variable.
//
// No dependencies: plain node, run via `npm run check:api`, in the
// mould of check-bundle-size.mjs (#165).

import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];

/**
 * Removes // and block comments while leaving string and template
 * literals untouched, so a "//" inside a URL or a regex-looking
 * sequence in prose cannot corrupt the scan. Template literals are
 * treated as opaque (the api modules' interpolations contain no
 * backticks or comment markers).
 */
export function stripComments(source) {
  let out = '';
  let i = 0;
  let mode = 'code'; // code | single | double | template | line | block
  while (i < source.length) {
    const ch = source[i];
    const next = source[i + 1] ?? '';
    if (mode === 'code') {
      if (ch === '/' && next === '/') { mode = 'line'; i += 2; continue; }
      if (ch === '/' && next === '*') { mode = 'block'; i += 2; continue; }
      if (ch === "'") mode = 'single';
      else if (ch === '"') mode = 'double';
      else if (ch === '`') mode = 'template';
      out += ch;
      i += 1;
      continue;
    }
    if (mode === 'line') {
      if (ch === '\n') { mode = 'code'; out += ch; }
      i += 1;
      continue;
    }
    if (mode === 'block') {
      if (ch === '*' && next === '/') { mode = 'code'; i += 2; continue; }
      if (ch === '\n') out += ch; // keep line numbers roughly aligned
      i += 1;
      continue;
    }
    // string modes: copy verbatim, honouring backslash escapes
    out += ch;
    if (ch === '\\') {
      if (i + 1 < source.length) { out += source[i + 1]; i += 2; continue; }
      i += 1;
      continue;
    }
    if ((mode === 'single' && ch === "'")
      || (mode === 'double' && ch === '"')
      || (mode === 'template' && ch === '`')) {
      mode = 'code';
    }
    i += 1;
  }
  return out;
}

/** Reads the string literal starting at `start` (a quote char). */
function readStringLiteral(source, start) {
  const quote = source[start];
  let i = start + 1;
  let content = '';
  while (i < source.length) {
    const ch = source[i];
    if (ch === '\\') {
      content += ch + (source[i + 1] ?? '');
      i += 2;
      continue;
    }
    if (ch === quote) return { content, end: i + 1 };
    content += ch;
    i += 1;
  }
  return { content, end: i };
}

/** `${encodeURIComponent(input.itemId)}` -> `itemId`; fallback `param`. */
function paramName(expression) {
  let expr = expression.trim();
  const wrapped = expr.match(/^encodeURIComponent\((.*)\)$/s);
  if (wrapped) expr = wrapped[1].trim();
  const last = expr.split('.').pop() ?? '';
  const name = last.replace(/[^A-Za-z0-9_]/g, '');
  return name || 'param';
}

/**
 * Converts a raw URL literal (template interpolations still in
 * ${...} form) to a display path: interpolations become {name},
 * and the query string / fragment are dropped.
 */
export function templateToPath(raw) {
  let path = '';
  let i = 0;
  while (i < raw.length) {
    if (raw[i] === '$' && raw[i + 1] === '{') {
      let depth = 1;
      let j = i + 2;
      while (j < raw.length && depth > 0) {
        if (raw[j] === '{') depth += 1;
        else if (raw[j] === '}') depth -= 1;
        j += 1;
      }
      path += `{${paramName(raw.slice(i + 2, j - 1))}}`;
      i = j;
      continue;
    }
    path += raw[i];
    i += 1;
  }
  return path.split(/[?#]/)[0];
}

/**
 * The shared axios instance has baseURL '/api', so module URLs are
 * relative ('/items'); client.ts's raw axios refresh call and the
 * EventSource URL carry the full '/api/...' path already. Both forms
 * normalise to the full path the OpenAPI document uses.
 */
export function toFullApiPath(path) {
  let p = path.startsWith('/') ? path : `/${path}`;
  if (p.length > 1 && p.endsWith('/')) p = p.slice(0, -1);
  if (p === '/api' || p.startsWith('/api/')) return p;
  return `/api${p}`;
}

/**
 * Param-name-insensitive canonical form: any segment containing a
 * {param} becomes '{}', so {id}, {itemId} and ${userId} all compare
 * equal at the same position. Literal segments must match exactly.
 */
export function canonicalizePath(path) {
  return path
    .split('/')
    .map((segment) => (segment.includes('{') ? '{}' : segment))
    .join('/');
}

/**
 * Extracts the api calls from one module's source text.
 * Returns { calls, unextractable } where calls are
 * { method, path } with full /api paths ({name} params), and
 * unextractable counts api/axios/EventSource call sites whose URL
 * argument is not a string literal.
 */
export function extractApiCalls(source) {
  const clean = stripComments(source);
  const calls = [];
  let unextractable = 0;

  const record = (method, fromIndex, parenConsumed) => {
    // The URL must be the call's first argument as a string literal.
    // Generic type arguments (<ApiResponse<Page<Item>>>) sit between
    // the method token and the argument-list '(' and contain no parens
    // in this codebase, so the first '(' after the method token opens
    // the argument list; the first non-space token after it must be
    // the URL literal — anything else (a variable, an expression) is
    // unextractable and fails the gate rather than being skipped.
    let i = fromIndex;
    if (!parenConsumed) {
      let opened = false;
      while (i < clean.length && i < fromIndex + 800) {
        if (clean[i] === '(') { opened = true; i += 1; break; }
        if (clean[i] === ';') break;
        i += 1;
      }
      if (!opened) { unextractable += 1; return; }
    }
    while (i < clean.length && /\s/.test(clean[i])) i += 1;
    const ch = clean[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      const { content } = readStringLiteral(clean, i);
      if (content.startsWith('/')) {
        calls.push({ method, path: toFullApiPath(templateToPath(content)) });
      } else {
        unextractable += 1;
      }
      return;
    }
    unextractable += 1;
  };

  const callPattern = /\b(?:api|axios)\s*\.\s*(get|post|put|patch|delete)\b/g;
  let match;
  while ((match = callPattern.exec(clean)) !== null) {
    record(match[1].toUpperCase(), match.index + match[0].length, false);
  }

  const eventSourcePattern = /\bnew\s+EventSource\s*\(/g;
  while ((match = eventSourcePattern.exec(clean)) !== null) {
    record('GET', match.index + match[0].length, true);
  }

  return { calls, unextractable };
}

/** Builds canonical-path -> sorted method list from an OpenAPI doc. */
export function specOperations(spec) {
  const operations = new Map();
  for (const [specPath, pathItem] of Object.entries(spec?.paths ?? {})) {
    const methods = Object.keys(pathItem ?? {})
      .filter((key) => HTTP_METHODS.includes(key.toLowerCase()))
      .map((key) => key.toUpperCase())
      .sort();
    if (methods.length > 0) operations.set(canonicalizePath(specPath), methods);
  }
  return operations;
}

/**
 * Pure drift check. `calls` are extractApiCalls results (any number of
 * modules concatenated; duplicates collapse). Returns
 * { ok, checked, violations } — one violation per distinct drifted
 * call: a path absent from the document ("missing path"), or a path
 * present without the called method ("wrong method").
 */
export function checkApiDrift(calls, spec) {
  const operations = specOperations(spec);
  const distinct = new Map();
  for (const call of calls) {
    distinct.set(`${call.method} ${canonicalizePath(call.path)}`, call);
  }
  const violations = [];
  for (const call of distinct.values()) {
    const methods = operations.get(canonicalizePath(call.path));
    if (!methods) {
      violations.push(`${call.method} ${call.path} — missing path: not in the OpenAPI document`);
    } else if (!methods.includes(call.method)) {
      violations.push(
        `${call.method} ${call.path} — wrong method: the OpenAPI document has ${methods.join(', ')} for this path`,
      );
    }
  }
  return { ok: violations.length === 0, checked: distinct.size, violations };
}

/**
 * Shape pinning (backlog #258). A pin is { method, path, request?,
 * response? } where request/response are field maps for the request
 * body and the envelope's data object. A field spec is a type string
 * ("string" | "integer" | "number" | "boolean" | "array" | "object")
 * or { type, required?, items?, fields?, enum? }.
 */

/** Follows $ref chains (components.schemas) until a concrete schema. */
export function resolveSchema(schema, spec, seen = new Set()) {
  let current = schema;
  while (current && typeof current.$ref === 'string') {
    const ref = current.$ref;
    if (seen.has(ref)) return null; // reference cycle: unresolvable
    seen.add(ref);
    const name = ref.replace(/^#\/components\/schemas\//, '');
    current = spec?.components?.schemas?.[name] ?? null;
    if (!current) return null;
  }
  return current ?? null;
}

/** Expands oneOf/anyOf into variants; any other schema is one variant. */
export function schemaVariants(schema, spec) {
  const resolved = resolveSchema(schema, spec);
  if (!resolved) return [];
  const branches = resolved.oneOf ?? resolved.anyOf;
  if (Array.isArray(branches)) {
    return branches.map((branch) => resolveSchema(branch, spec)).filter(Boolean);
  }
  return [resolved];
}

/** TS `number` accepts OpenAPI `integer` or `number`; all else exact. */
export function typeMatches(pinnedType, schemaType) {
  if (pinnedType === 'number') return schemaType === 'integer' || schemaType === 'number';
  return pinnedType === schemaType;
}

function normalizeFieldSpec(spec) {
  return typeof spec === 'string' ? { type: spec } : spec;
}

/**
 * Checks a pinned field map against an object schema's properties.
 * Returns violation strings; `at` is the dotted path for messages.
 * Missing required fields and type mismatches fail; optional fields
 * (required: false) are type-checked only when present; nested
 * objects/arrays recurse; an enum pin requires every pinned value to
 * still be in the document's enum when the document declares one.
 */
export function checkFieldMap(fields, schema, spec, at = '') {
  const violations = [];
  const resolved = resolveSchema(schema, spec);
  if (!resolved || typeof resolved !== 'object') {
    return [`${at || 'schema'} is not a resolvable object schema`];
  }
  if (resolved.type && resolved.type !== 'object' && !resolved.properties) {
    return [`${at || 'schema'} has type ${resolved.type}, not object`];
  }
  const properties = resolved.properties ?? {};
  for (const [name, rawField] of Object.entries(fields)) {
    const field = normalizeFieldSpec(rawField);
    const label = at ? `${at}.${name}` : name;
    const property = properties[name];
    if (!property) {
      if (field.required !== false) violations.push(`field "${label}" missing`);
      continue;
    }
    const propSchema = resolveSchema(property, spec);
    if (!propSchema) {
      violations.push(`field "${label}" has an unresolvable $ref`);
      continue;
    }
    if (propSchema.type && !typeMatches(field.type, propSchema.type)) {
      violations.push(
        `field "${label}" type mismatch: pinned ${field.type}, document has ${propSchema.type}`,
      );
      continue;
    }
    if (!propSchema.type && field.type === 'object' && !propSchema.properties) {
      violations.push(`field "${label}" has no type in the document`);
      continue;
    }
    if (field.type === 'object' && field.fields) {
      violations.push(...checkFieldMap(field.fields, propSchema, spec, label));
    }
    if (field.type === 'array' && field.items) {
      const itemSpec = normalizeFieldSpec(field.items);
      const items = propSchema.items ? resolveSchema(propSchema.items, spec) : null;
      if (!items) {
        violations.push(`field "${label}" is an array with no item schema in the document`);
      } else if (items.type && !typeMatches(itemSpec.type, items.type)) {
        violations.push(
          `field "${label}" item type mismatch: pinned ${itemSpec.type}, document has ${items.type}`,
        );
      } else if (itemSpec.type === 'object' && itemSpec.fields) {
        violations.push(...checkFieldMap(itemSpec.fields, items, spec, `${label}[]`));
      }
    }
    if (Array.isArray(field.enum) && Array.isArray(propSchema.enum)) {
      const dropped = field.enum.filter((value) => !propSchema.enum.includes(value));
      if (dropped.length > 0) {
        violations.push(`field "${label}" lost enum value(s): ${dropped.join(', ')}`);
      }
    }
  }
  return violations;
}

/** Finds one operation by param-name-insensitive path + method. */
export function operationByMethodPath(spec, method, path) {
  const wanted = canonicalizePath(path);
  for (const [specPath, pathItem] of Object.entries(spec?.paths ?? {})) {
    if (canonicalizePath(specPath) !== wanted) continue;
    const operation = pathItem?.[method.toLowerCase()];
    if (operation) return operation;
  }
  return null;
}

/**
 * Unwraps one response object's envelope data schemas: one entry per
 * oneOf/anyOf variant of the envelope's data, each with the envelope
 * schema itself for the code/message check. Returns [] when the
 * response carries no {code, message, data} envelope (a bare object
 * or a bare DTO is not an envelope and never counts as a carrier).
 */
export function responseDataSchemasForResponse(response, spec) {
  const content = response?.content ?? {};
  const media = content['application/json'] ?? Object.values(content)[0];
  if (!media?.schema) return [];
  const envelope = resolveSchema(media.schema, spec);
  if (!envelope || !envelope.properties?.data) return [];
  return schemaVariants(envelope.properties.data, spec).map((dataSchema) => ({
    envelope,
    dataSchema,
  }));
}

/**
 * Collects the envelope data schemas an operation carries, one entry
 * per response whose schema unwraps to {code, message, data}. The raw
 * collection is still every response — checkShapeDrift narrows it to
 * the 2xx carriers when any exist (backlog #271), so a success-only
 * field cannot hide behind an error response carrying the old DTO;
 * operations with no 2xx envelope keep the pre-#271 fallback to any
 * carrier (the error-carried pins from #258 still pass on it).
 */
export function responseDataSchemas(operation, spec) {
  const found = [];
  for (const [statusCode, response] of Object.entries(operation?.responses ?? {})) {
    for (const entry of responseDataSchemasForResponse(response, spec)) {
      found.push({ statusCode, ...entry });
    }
  }
  return found;
}

/**
 * The 2xx subset of responseDataSchemas — the success carriers. A
 * "2XX" wildcard counts as success too (its code starts with '2').
 */
export function successResponseDataSchemas(operation, spec) {
  return responseDataSchemas(operation, spec).filter((candidate) =>
    String(candidate.statusCode).startsWith('2'),
  );
}

/**
 * Checks one pinned response data shape against one carried data
 * schema. Three forms (backlog #264 adds the last two to #258's
 * field-map form):
 *   - a field map (object) — the data object must carry every pinned
 *     field with its pinned type (checkFieldMap);
 *   - a bare type string, e.g. 'integer' — the data itself is a scalar
 *     (the unread-count and read-all endpoints answer a bare count in
 *     the envelope, no fields to pin);
 *   - { type: 'array', items: <spec> } — the data is a list (the
 *     suggestions / similar / price-history / preferences reads); the
 *     item spec follows the same forms as a field-map array item.
 * The array form is recognised only when BOTH `type: 'array'` and an
 * `items` key are present, so a field map that happens to pin a field
 * named `type` (NotificationDto's `type` enum) can never be mistaken
 * for it — no pinned DTO in this codebase carries a field named
 * `items` alongside one named `type`.
 */
export function checkResponseData(pinResponse, dataSchema, spec) {
  if (typeof pinResponse === 'string') {
    const resolved = resolveSchema(dataSchema, spec);
    if (!resolved) return ['response data schema is unresolvable'];
    if (resolved.type && !typeMatches(pinResponse, resolved.type)) {
      return [
        `response data type mismatch: pinned ${pinResponse}, document has ${resolved.type}`,
      ];
    }
    if (!resolved.type) return ['response data has no type in the document'];
    return [];
  }
  if (
    pinResponse &&
    typeof pinResponse === 'object' &&
    pinResponse.type === 'array' &&
    pinResponse.items !== undefined
  ) {
    const resolved = resolveSchema(dataSchema, spec);
    if (!resolved) return ['response data schema is unresolvable'];
    if (resolved.type && resolved.type !== 'array') {
      return [
        `response data type mismatch: pinned array, document has ${resolved.type}`,
      ];
    }
    const items = resolved.items ? resolveSchema(resolved.items, spec) : null;
    if (!items) {
      return ['response data is an array with no item schema in the document'];
    }
    const itemSpec = normalizeFieldSpec(pinResponse.items);
    if (itemSpec.type === 'object' && itemSpec.fields) {
      return checkFieldMap(itemSpec.fields, items, spec, '');
    }
    if (items.type && !typeMatches(itemSpec.type, items.type)) {
      return [
        `response data item type mismatch: pinned ${itemSpec.type}, document has ${items.type}`,
      ];
    }
    if (!items.type) return ['response data item has no type in the document'];
    return [];
  }
  return checkFieldMap(pinResponse, dataSchema, spec, '');
}

/**
 * Pure shape-drift check over pins (see api-shape-pins.mjs).
 * Returns { ok, checked, responsePinned, unpinnedResponses, violations }.
 * A pin without a `response` key is request-only: its operation is
 * recorded in unpinnedResponses (visible, not silently checked) and
 * never fails for want of a response shape. A pin WITH a response
 * fails when the document carries no typed response at all, or when
 * no carried data schema satisfies the pinned shape; the closest
 * candidate's failures are reported so the drift is actionable.
 * Since backlog #271 a plain `response` pin must pass against a 2xx
 * carrier when one exists (see the narrowing above), and a
 * `responseByStatus` pin checks each status's own data schema.
 */
export function checkShapeDrift(pins, spec) {
  const violations = [];
  const unpinnedResponses = [];
  let responsePinned = 0;
  for (const pin of pins) {
    const label = `${pin.method} ${pin.path}`;
    const operation = operationByMethodPath(spec, pin.method, pin.path);
    if (!operation) {
      violations.push(`${label} — pinned operation not in the OpenAPI document`);
      continue;
    }
    if (pin.request) {
      const requestBody = operation.requestBody;
      const content = requestBody?.content ?? {};
      const jsonMedia = content['application/json'];
      if (jsonMedia?.schema) {
        violations.push(
          ...checkFieldMap(pin.request, jsonMedia.schema, spec, '').map(
            (v) => `${label} request: ${v}`,
          ),
        );
      } else {
        // Non-JSON request (multipart in this codebase): springdoc
        // models @RequestParam scalars as query parameters and puts
        // only the file part in the multipart schema, so the pinned
        // request shape is the union of both sources. A pinned field
        // must appear in one of them with its pinned type; a field in
        // neither fails. JSON endpoints never take this branch, so
        // their pins stay body-only and cannot be masked by a query
        // parameter of the same name.
        const media = Object.values(content)[0];
        const bodySchema = media?.schema ? resolveSchema(media.schema, spec) : null;
        const properties = { ...(bodySchema?.properties ?? {}) };
        for (const param of operation.parameters ?? []) {
          if (param?.in === 'query' && param?.name && param?.schema) {
            properties[param.name] = param.schema;
          }
        }
        if (Object.keys(properties).length === 0) {
          violations.push(
            `${label} — pinned request fields but the operation has no request body`,
          );
        } else {
          violations.push(
            ...checkFieldMap(pin.request, { type: 'object', properties }, spec, '').map(
              (v) => `${label} request: ${v}`,
            ),
          );
        }
      }
    }
    if (pin.responseByStatus !== undefined) {
      // Backlog #271: one pin per success status — an endpoint whose
      // success body branches by status (register 200 vs 201, login
      // 200 vs 202) pins each variant against its own status's data
      // schema, never against a sibling status's shape.
      responsePinned += 1;
      for (const [status, fields] of Object.entries(pin.responseByStatus)) {
        const statusLabel = `${label} ${status}`;
        const response = operation.responses?.[status];
        if (!response) {
          violations.push(`${statusLabel} — no ${status} response in the document`);
          continue;
        }
        const entries = responseDataSchemasForResponse(response, spec);
        if (entries.length === 0) {
          violations.push(
            `${statusLabel} — the ${status} response carries no typed envelope data`,
          );
          continue;
        }
        for (const entry of entries) {
          const envelopeViolations = checkFieldMap(
            { code: 'integer', message: 'string' },
            entry.envelope,
            spec,
            '',
          );
          violations.push(...envelopeViolations.map((v) => `${statusLabel}: ${v}`));
        }
        let best = null;
        for (const entry of entries) {
          const fieldViolations = checkResponseData(fields, entry.dataSchema, spec);
          if (fieldViolations.length === 0) {
            best = [];
            break;
          }
          if (best === null || fieldViolations.length < best.length) best = fieldViolations;
        }
        if (best !== null && best.length > 0) {
          violations.push(
            `${statusLabel} — no ${status} response in the document carries all pinned fields (closest: ${best.join('; ')})`,
          );
        }
      }
      continue;
    }
    if (pin.response === undefined) {
      unpinnedResponses.push(
        pin.responseNote ? `${label} — ${pin.responseNote}` : `${label} — no response pin`,
      );
      continue;
    }
    responsePinned += 1;
    const allCandidates = responseDataSchemas(operation, spec);
    if (allCandidates.length === 0) {
      violations.push(
        `${label} — pinned response fields but the document carries no typed response for this operation`,
      );
      continue;
    }
    // Backlog #271: prefer the success carriers. When a 2xx response
    // carries an envelope, the pin must pass against it — an error
    // response carrying the old DTO must not mask a success-only
    // field that disappeared from the 2xx schema. Operations with no
    // 2xx envelope keep the pre-#271 fallback to any carrier.
    const successCandidates = successResponseDataSchemas(operation, spec);
    const candidates = successCandidates.length > 0 ? successCandidates : allCandidates;
    for (const candidate of candidates) {
      const envelopeViolations = checkFieldMap(
        { code: 'integer', message: 'string' },
        candidate.envelope,
        spec,
        '',
      );
      violations.push(...envelopeViolations.map((v) => `${label}: ${v}`));
    }
    let best = null;
    for (const candidate of candidates) {
      const fieldViolations = checkResponseData(pin.response, candidate.dataSchema, spec);
      if (fieldViolations.length === 0) {
        best = [];
        break;
      }
      if (best === null || fieldViolations.length < best.length) best = fieldViolations;
    }
    if (best !== null && best.length > 0) {
      violations.push(
        `${label} — no response in the document carries all pinned fields (closest: ${best.join('; ')})`,
      );
    }
  }
  return {
    ok: violations.length === 0,
    checked: pins.length,
    responsePinned,
    unpinnedResponses,
    violations,
  };
}

function parseArgs(argv) {
  const args = { spec: null, apiDir: null, pins: null };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--spec') args.spec = argv[i + 1], i += 1;
    else if (argv[i] === '--api-dir') args.apiDir = argv[i + 1], i += 1;
    else if (argv[i] === '--pins') args.pins = argv[i + 1], i += 1;
    else if (!argv[i].startsWith('--') && !args.spec) args.spec = argv[i];
  }
  return args;
}

async function main() {
  const frontendDir = join(dirname(fileURLToPath(import.meta.url)), '..');
  const args = parseArgs(process.argv.slice(2));
  const specPath = args.spec
    ? resolve(process.cwd(), args.spec)
    : join(frontendDir, 'openapi.json');
  const apiDir = args.apiDir ? resolve(process.cwd(), args.apiDir) : join(frontendDir, 'src', 'api');

  let spec;
  try {
    spec = JSON.parse(readFileSync(specPath, 'utf8'));
  } catch {
    console.error(`No OpenAPI document found at ${specPath}.`);
    console.error('Export it from the backend contract-test path first:');
    console.error(
      '  OPENAPI_EXPORT_PATH=$PWD/frontend/openapi.json mvn -f backend/pom.xml test -Dtest=com.toni.marketplace.common.OpenApiExportTest',
    );
    process.exit(1);
  }

  const moduleNames = readdirSync(apiDir)
    .filter((name) => name.endsWith('.ts') && !name.includes('.test.'))
    .sort();
  const calls = [];
  let unextractable = 0;
  for (const name of moduleNames) {
    const found = extractApiCalls(readFileSync(join(apiDir, name), 'utf8'));
    calls.push(...found.calls);
    unextractable += found.unextractable;
  }

  if (calls.length === 0) {
    console.error('No api calls extracted — the gate must not pass vacuously.');
    process.exit(1);
  }
  if (unextractable > 0) {
    console.error(
      `${unextractable} api call site(s) have a non-literal URL and cannot be checked — give the call a string-literal URL or extend the extractor.`,
    );
    process.exit(1);
  }

  const operations = specOperations(spec);
  const operationCount = [...operations.values()].reduce((sum, m) => sum + m.length, 0);
  const result = checkApiDrift(calls, spec);
  console.log(
    `Checked ${result.checked} distinct frontend api calls against ${operationCount} OpenAPI operations (${operations.size} paths) from ${specPath}.`,
  );

  // Shape gate (backlog #258): pins live beside this script; --pins
  // lets fixture tests drive the gate against synthetic documents.
  const scriptDir = dirname(fileURLToPath(import.meta.url));
  const pinsPath = args.pins
    ? resolve(process.cwd(), args.pins)
    : join(scriptDir, 'api-shape-pins.mjs');
  let pins;
  try {
    pins = (await import(pathToFileURL(pinsPath).href)).API_SHAPE_PINS;
  } catch {
    console.error(`No shape pins found at ${pinsPath} (expected an API_SHAPE_PINS export).`);
    process.exit(1);
  }
  if (!Array.isArray(pins) || pins.length === 0) {
    console.error('Shape pins must be a non-empty array — the gate must not pass vacuously.');
    process.exit(1);
  }
  const shape = checkShapeDrift(pins, spec);
  console.log(
    `Checked ${shape.checked} pinned operations: request shapes on ${
      pins.filter((pin) => pin.request).length
    }, response shapes on ${shape.responsePinned}, responses unpinned on ${
      shape.unpinnedResponses.length
    } (see api-shape-pins.mjs header).`,
  );
  for (const unpinned of shape.unpinnedResponses) {
    console.log(`Shape unpinned: ${unpinned}`);
  }

  let failed = false;
  if (!result.ok) {
    for (const violation of result.violations) {
      console.error(`API DRIFT: ${violation}`);
    }
    failed = true;
  } else {
    console.log('No API drift: every frontend api call exists in the OpenAPI document.');
  }
  if (!shape.ok) {
    for (const violation of shape.violations) {
      console.error(`API SHAPE DRIFT: ${violation}`);
    }
    failed = true;
  } else {
    console.log('No API shape drift: every pinned field is present with its pinned type.');
  }
  if (failed) process.exit(1);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
