// API drift check (backlog #205).
//
// Why: the frontend has no codegen — every endpoint string and DTO type
// in frontend/src/api/*.ts is hand-written against the backend, and the
// backend-side contract test (#125, OpenApiContractTest) pins only the
// spec itself. A renamed or removed backend path therefore stayed green
// until a user clicked the dead call. This script is the other half of
// the contract: it extracts every method+path the frontend api modules
// call and fails when one is absent from the OpenAPI document.
//
// Honest scope: this pins paths and methods only — NOT payload shapes.
// A renamed request/response field passes this gate; DTO shape drift is
// what the api modules' TypeScript types and their tests are for. The
// header says exactly that so nobody reads more into a green run.
//
// How the spec gets here: the document is generated by springdoc from
// the controllers (the #95/#125 contract). It is exported by the
// env-gated OpenApiExportTest on the existing contract-test path:
//
//   OPENAPI_EXPORT_PATH=$PWD/frontend/openapi.json \
//     mvn -f backend/pom.xml test -Dtest=com.toni.marketplace.common.OpenApiExportTest
//
// The exported file is a build artifact (gitignored), never committed.
// CI runs exactly those two steps in the `api-drift` job, then
// `npm run check:api`. Locally: export once, then `npm run check:api`.
//
// Extraction rules (pinned by check-api-drift.test.mjs):
//   - calls on the shared `api` axios instance (baseURL '/api'), in both
//     forms used in this codebase: `api.get<...>(url)` and the chained
//     `api` newline `.get<...>(url)`; plus the one raw
//     `axios.post('/api/auth/refresh', ...)` in client.ts;
//   - `new EventSource(url)` counts as a GET (the #203 SSE stream);
//   - only *.ts modules under src/api are scanned, never *.test.* —
//     tests mock the api instance with fixture paths on purpose;
//   - comments are stripped first, so the doc comments that document
//     each endpoint ("GET /api/items/{id} — ...") are never mistaken
//     for calls;
//   - template interpolations (${id}, ${input.itemId},
//     ${encodeURIComponent(id)}) become path params, and matching is
//     param-name-insensitive: a segment that is a param on either side
//     matches a param segment on the other ({id} vs ${userId} is the
//     same call — the backend and the SPA name params independently);
//   - query strings are stripped (params travel via axios `params`,
//     and the one URL-carried query — the SSE ticket — is not part of
//     the path contract).
// A call whose URL is not a string literal fails the gate as
// unextractable rather than being skipped silently: drift must not be
// able to hide behind a variable.
//
// No dependencies: plain node, run via `npm run check:api`, in the
// mould of check-bundle-size.mjs (#165).

import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options'];

/**
 * Removes // and block comments while leaving string and template
 * literals untouched, so a "//" inside a URL or a regex-looking
 * sequence in prose cannot corrupt the scan. Template literals are
 * treated as opaque (the api modules' interpolations contain no
 * backticks or comment markers).
 */
export function stripComments(source) {
  let out = '';
  let i = 0;
  let mode = 'code'; // code | single | double | template | line | block
  while (i < source.length) {
    const ch = source[i];
    const next = source[i + 1] ?? '';
    if (mode === 'code') {
      if (ch === '/' && next === '/') { mode = 'line'; i += 2; continue; }
      if (ch === '/' && next === '*') { mode = 'block'; i += 2; continue; }
      if (ch === "'") mode = 'single';
      else if (ch === '"') mode = 'double';
      else if (ch === '`') mode = 'template';
      out += ch;
      i += 1;
      continue;
    }
    if (mode === 'line') {
      if (ch === '\n') { mode = 'code'; out += ch; }
      i += 1;
      continue;
    }
    if (mode === 'block') {
      if (ch === '*' && next === '/') { mode = 'code'; i += 2; continue; }
      if (ch === '\n') out += ch; // keep line numbers roughly aligned
      i += 1;
      continue;
    }
    // string modes: copy verbatim, honouring backslash escapes
    out += ch;
    if (ch === '\\') {
      if (i + 1 < source.length) { out += source[i + 1]; i += 2; continue; }
      i += 1;
      continue;
    }
    if ((mode === 'single' && ch === "'")
      || (mode === 'double' && ch === '"')
      || (mode === 'template' && ch === '`')) {
      mode = 'code';
    }
    i += 1;
  }
  return out;
}

/** Reads the string literal starting at `start` (a quote char). */
function readStringLiteral(source, start) {
  const quote = source[start];
  let i = start + 1;
  let content = '';
  while (i < source.length) {
    const ch = source[i];
    if (ch === '\\') {
      content += ch + (source[i + 1] ?? '');
      i += 2;
      continue;
    }
    if (ch === quote) return { content, end: i + 1 };
    content += ch;
    i += 1;
  }
  return { content, end: i };
}

/** `${encodeURIComponent(input.itemId)}` -> `itemId`; fallback `param`. */
function paramName(expression) {
  let expr = expression.trim();
  const wrapped = expr.match(/^encodeURIComponent\((.*)\)$/s);
  if (wrapped) expr = wrapped[1].trim();
  const last = expr.split('.').pop() ?? '';
  const name = last.replace(/[^A-Za-z0-9_]/g, '');
  return name || 'param';
}

/**
 * Converts a raw URL literal (template interpolations still in
 * ${...} form) to a display path: interpolations become {name},
 * and the query string / fragment are dropped.
 */
export function templateToPath(raw) {
  let path = '';
  let i = 0;
  while (i < raw.length) {
    if (raw[i] === '$' && raw[i + 1] === '{') {
      let depth = 1;
      let j = i + 2;
      while (j < raw.length && depth > 0) {
        if (raw[j] === '{') depth += 1;
        else if (raw[j] === '}') depth -= 1;
        j += 1;
      }
      path += `{${paramName(raw.slice(i + 2, j - 1))}}`;
      i = j;
      continue;
    }
    path += raw[i];
    i += 1;
  }
  return path.split(/[?#]/)[0];
}

/**
 * The shared axios instance has baseURL '/api', so module URLs are
 * relative ('/items'); client.ts's raw axios refresh call and the
 * EventSource URL carry the full '/api/...' path already. Both forms
 * normalise to the full path the OpenAPI document uses.
 */
export function toFullApiPath(path) {
  let p = path.startsWith('/') ? path : `/${path}`;
  if (p.length > 1 && p.endsWith('/')) p = p.slice(0, -1);
  if (p === '/api' || p.startsWith('/api/')) return p;
  return `/api${p}`;
}

/**
 * Param-name-insensitive canonical form: any segment containing a
 * {param} becomes '{}', so {id}, {itemId} and ${userId} all compare
 * equal at the same position. Literal segments must match exactly.
 */
export function canonicalizePath(path) {
  return path
    .split('/')
    .map((segment) => (segment.includes('{') ? '{}' : segment))
    .join('/');
}

/**
 * Extracts the api calls from one module's source text.
 * Returns { calls, unextractable } where calls are
 * { method, path } with full /api paths ({name} params), and
 * unextractable counts api/axios/EventSource call sites whose URL
 * argument is not a string literal.
 */
export function extractApiCalls(source) {
  const clean = stripComments(source);
  const calls = [];
  let unextractable = 0;

  const record = (method, fromIndex, parenConsumed) => {
    // The URL must be the call's first argument as a string literal.
    // Generic type arguments (<ApiResponse<Page<Item>>>) sit between
    // the method token and the argument-list '(' and contain no parens
    // in this codebase, so the first '(' after the method token opens
    // the argument list; the first non-space token after it must be
    // the URL literal — anything else (a variable, an expression) is
    // unextractable and fails the gate rather than being skipped.
    let i = fromIndex;
    if (!parenConsumed) {
      let opened = false;
      while (i < clean.length && i < fromIndex + 800) {
        if (clean[i] === '(') { opened = true; i += 1; break; }
        if (clean[i] === ';') break;
        i += 1;
      }
      if (!opened) { unextractable += 1; return; }
    }
    while (i < clean.length && /\s/.test(clean[i])) i += 1;
    const ch = clean[i];
    if (ch === "'" || ch === '"' || ch === '`') {
      const { content } = readStringLiteral(clean, i);
      if (content.startsWith('/')) {
        calls.push({ method, path: toFullApiPath(templateToPath(content)) });
      } else {
        unextractable += 1;
      }
      return;
    }
    unextractable += 1;
  };

  const callPattern = /\b(?:api|axios)\s*\.\s*(get|post|put|patch|delete)\b/g;
  let match;
  while ((match = callPattern.exec(clean)) !== null) {
    record(match[1].toUpperCase(), match.index + match[0].length, false);
  }

  const eventSourcePattern = /\bnew\s+EventSource\s*\(/g;
  while ((match = eventSourcePattern.exec(clean)) !== null) {
    record('GET', match.index + match[0].length, true);
  }

  return { calls, unextractable };
}

/** Builds canonical-path -> sorted method list from an OpenAPI doc. */
export function specOperations(spec) {
  const operations = new Map();
  for (const [specPath, pathItem] of Object.entries(spec?.paths ?? {})) {
    const methods = Object.keys(pathItem ?? {})
      .filter((key) => HTTP_METHODS.includes(key.toLowerCase()))
      .map((key) => key.toUpperCase())
      .sort();
    if (methods.length > 0) operations.set(canonicalizePath(specPath), methods);
  }
  return operations;
}

/**
 * Pure drift check. `calls` are extractApiCalls results (any number of
 * modules concatenated; duplicates collapse). Returns
 * { ok, checked, violations } — one violation per distinct drifted
 * call: a path absent from the document ("missing path"), or a path
 * present without the called method ("wrong method").
 */
export function checkApiDrift(calls, spec) {
  const operations = specOperations(spec);
  const distinct = new Map();
  for (const call of calls) {
    distinct.set(`${call.method} ${canonicalizePath(call.path)}`, call);
  }
  const violations = [];
  for (const call of distinct.values()) {
    const methods = operations.get(canonicalizePath(call.path));
    if (!methods) {
      violations.push(`${call.method} ${call.path} — missing path: not in the OpenAPI document`);
    } else if (!methods.includes(call.method)) {
      violations.push(
        `${call.method} ${call.path} — wrong method: the OpenAPI document has ${methods.join(', ')} for this path`,
      );
    }
  }
  return { ok: violations.length === 0, checked: distinct.size, violations };
}

function parseArgs(argv) {
  const args = { spec: null, apiDir: null };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--spec') args.spec = argv[i + 1], i += 1;
    else if (argv[i] === '--api-dir') args.apiDir = argv[i + 1], i += 1;
    else if (!argv[i].startsWith('--') && !args.spec) args.spec = argv[i];
  }
  return args;
}

function main() {
  const frontendDir = join(dirname(fileURLToPath(import.meta.url)), '..');
  const args = parseArgs(process.argv.slice(2));
  const specPath = args.spec
    ? resolve(process.cwd(), args.spec)
    : join(frontendDir, 'openapi.json');
  const apiDir = args.apiDir ? resolve(process.cwd(), args.apiDir) : join(frontendDir, 'src', 'api');

  let spec;
  try {
    spec = JSON.parse(readFileSync(specPath, 'utf8'));
  } catch {
    console.error(`No OpenAPI document found at ${specPath}.`);
    console.error('Export it from the backend contract-test path first:');
    console.error(
      '  OPENAPI_EXPORT_PATH=$PWD/frontend/openapi.json mvn -f backend/pom.xml test -Dtest=com.toni.marketplace.common.OpenApiExportTest',
    );
    process.exit(1);
  }

  const moduleNames = readdirSync(apiDir)
    .filter((name) => name.endsWith('.ts') && !name.includes('.test.'))
    .sort();
  const calls = [];
  let unextractable = 0;
  for (const name of moduleNames) {
    const found = extractApiCalls(readFileSync(join(apiDir, name), 'utf8'));
    calls.push(...found.calls);
    unextractable += found.unextractable;
  }

  if (calls.length === 0) {
    console.error('No api calls extracted — the gate must not pass vacuously.');
    process.exit(1);
  }
  if (unextractable > 0) {
    console.error(
      `${unextractable} api call site(s) have a non-literal URL and cannot be checked — give the call a string-literal URL or extend the extractor.`,
    );
    process.exit(1);
  }

  const operations = specOperations(spec);
  const operationCount = [...operations.values()].reduce((sum, m) => sum + m.length, 0);
  const result = checkApiDrift(calls, spec);
  console.log(
    `Checked ${result.checked} distinct frontend api calls against ${operationCount} OpenAPI operations (${operations.size} paths) from ${specPath}.`,
  );
  console.log('Scope: paths + methods only — payload shapes are not pinned by this gate.');
  if (!result.ok) {
    for (const violation of result.violations) {
      console.error(`API DRIFT: ${violation}`);
    }
    process.exit(1);
  }
  console.log('No API drift: every frontend api call exists in the OpenAPI document.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
